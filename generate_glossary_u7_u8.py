def main():
    by_key = get_u7_u8_translations()

    # Load token data
    with open("paragraphs_words_tokens.json", "r", encoding="utf-8") as f:
        tokens_data = json.load(f)

    # Load unit metadata for vocabulary additions
    with open("data_units.json", "r", encoding="utf-8") as f:
        units_data = json.load(f)

    words = {}

    # 1. Add base vocabulary from Units 7 & 8 tables
    for u_id in ["7", "8"]:
        u = units_data[u_id]
        for v in u.get("vocabulary", []):
            w = v.get("word", "").strip()
            pl = v.get("plural", "").strip()
            m = v.get("meaning", "").strip()
            if w:
                words[w] = m
                words[strip_tashkeel(w)] = m
            if pl and pl != "—":
                words[pl] = f"мн. от {w}: {m}"
                words[strip_tashkeel(pl)] = f"мн. от {w}: {m}"

        for vb in u.get("verbs", []):
            m = vb.get("meaning", "").strip()
            pa = vb.get("past", "").strip()
            pr = vb.get("present", "").strip()
            ms = vb.get("masdar", "").strip()
            if pa:
                words[pa] = f"{m} (прош.)"
                words[strip_tashkeel(pa)] = f"{m} (прош.)"
            if pr:
                words[pr] = f"{m} (наст.)"
                words[strip_tashkeel(pr)] = f"{m} (наст.)"
            if ms:
                words[ms] = f"{m} (масдар)"
                words[strip_tashkeel(ms)] = f"{m} (масдар)"

        for c in u.get("collocations", []):
            p = c.get("phrase", "").strip()
            m = c.get("meaning", "").strip()
            if p:
                words[p] = m
                words[strip_tashkeel(p)] = m

    # 2. Add individual tokens from Unit 7 and Unit 8 into words dictionary
    for u_id in ["7", "8"]:
        for p_id in sorted(tokens_data[u_id].keys(), key=int):
            for t in tokens_data[u_id][p_id]:
                key = f"{u_id}_{p_id}_{t['idx']}"
                tr = by_key.get(key, "")
                w = t["word"]
                if w and tr and w not in ["-", "•"]:
                    if w not in words:
                        words[w] = tr
                    plain = strip_tashkeel(w)
                    if plain and plain not in words:
                        words[plain] = tr

    result = {
        "by_key": by_key,
        "words": words
    }

    with open("glossary_u7_u8.json", "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)

    print(f"Successfully generated glossary_u7_u8.json!")
    print(f"Total tokens in by_key: {len(by_key)}")
    print(f"Total entries in words: {len(words)}")

if __name__ == "__main__":
    main()
