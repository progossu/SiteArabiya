with open('paragraphs_words_tokens.json', 'r', encoding='utf-8') as f:
    pwt = json.load(f)

word_translations = defaultdict(list)
by_key = {}

for u_id, u_data in [("1", unit1_data), ("2", unit2_data)]:
    for p_id in sorted(pwt[u_id].keys(), key=int):
        for t in pwt[u_id][p_id]:
            idx = t['idx']
            word = t['word']
            key = f"{u_id}_{p_id}_{idx}"
            trans = u_data[p_id][idx]
            by_key[key] = trans
            word_translations[word].append(trans)

