words_dict = {}
for word, trans_list in word_translations.items():
    if word in canonical_words:
        words_dict[word] = canonical_words[word]
    else:
        counts = Counter(trans_list)
        most_common, _ = counts.most_common(1)[0]
        words_dict[word] = most_common

# Build glossary
