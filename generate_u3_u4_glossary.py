def validate_and_generate():
    with open("paragraphs_words_tokens.json", "r", encoding="utf-8") as f:
        tokens_data = json.load(f)

    by_key = {}
    words_map = {}
    total_tokens = 0

    # Process Unit 3
    for p_id in sorted(tokens_data["3"].keys(), key=lambda x: int(x)):
        toks = tokens_data["3"][p_id]
        trans_dict = u3_translations.get(p_id, {})
        for t in toks:
            idx = t["idx"]
            word = t["word"]
            if idx not in trans_dict:
                raise ValueError(f"Missing translation for Unit 3 Paragraph {p_id} Index {idx} ('{word}')")
            tr = trans_dict[idx].strip()
            if not tr:
                raise ValueError(f"Empty translation for Unit 3 Paragraph {p_id} Index {idx} ('{word}')")
            key = f"3_{p_id}_{idx}"
            by_key[key] = tr
            words_map[word] = tr
            total_tokens += 1

    # Process Unit 4
    for p_id in sorted(tokens_data["4"].keys(), key=lambda x: int(x)):
        toks = tokens_data["4"][p_id]
        trans_dict = u4_translations.get(p_id, {})
        for t in toks:
            idx = t["idx"]
            word = t["word"]
            if idx not in trans_dict:
                raise ValueError(f"Missing translation for Unit 4 Paragraph {p_id} Index {idx} ('{word}')")
            tr = trans_dict[idx].strip()
            if not tr:
                raise ValueError(f"Empty translation for Unit 4 Paragraph {p_id} Index {idx} ('{word}')")
            key = f"4_{p_id}_{idx}"
            by_key[key] = tr
            words_map[word] = tr
            total_tokens += 1

    print(f"Validation successful! Total tokens processed: {total_tokens}")
    print(f"Total keys in by_key: {len(by_key)}")
    print(f"Total entries in words: {len(words_map)}")

    glossary_data = {
        "by_key": by_key,
        "words": words_map
    }

    with open("glossary_u3_u4.json", "w", encoding="utf-8") as f_out:
        json.dump(glossary_data, f_out, ensure_ascii=False, indent=2)

    print("Successfully wrote glossary_u3_u4.json")

if __name__ == "__main__":
    validate_and_generate()
