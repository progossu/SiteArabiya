translations["6_6_33"] = "средства (деньги)"
translations["6_6_34"] = "многие (огромные)"

# Load tokens file
with open("paragraphs_words_tokens.json", "r", encoding="utf-8") as f:
    tokens_data = json.load(f)

# Build words map
words_map = {}
missing = []
total_tokens = 0

for u_id in ["5", "6"]:
    for p_id in sorted(tokens_data[u_id].keys(), key=lambda x: int(x)):
        for t in tokens_data[u_id][p_id]:
            total_tokens += 1
            key = f"{u_id}_{p_id}_{t['idx']}"
            if key not in translations:
                missing.append((key, t["word"]))
            else:
                tr = translations[key]
                w = t["word"]
                if w not in words_map:
                    words_map[w] = tr

print(f"Total tokens in U5 & U6: {total_tokens}")
print(f"Total translations defined: {len(translations)}")
print(f"Missing keys: {len(missing)}")
if missing:
    print(f"First 10 missing: {missing[:10]}")
    exit(1)

# Check for empty translations
empty = [k for k, v in translations.items() if not v or not v.strip()]
print(f"Empty translations: {len(empty)}")
if empty:
    print(f"Empty keys: {empty}")
    exit(1)

result = {
    "by_key": translations,
    "words": words_map
}

out_path = "glossary_u5_u6.json"
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(result, f, ensure_ascii=False, indent=2)

print(f"Successfully saved {out_path}!")
print(f"by_key count: {len(result['by_key'])}")
print(f"distinct words count: {len(result['words'])}")
